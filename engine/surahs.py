def _register() -> None:
    from .normalize import fold

    for n, name in NAMES_FA.items():
        ALIASES[fold(name)] = n
        ALIASES[fold("ال" + name)] = n
    for alias, n in _EXTRA.items():
        ALIASES[fold(alias)] = n


_register()


def resolve_surah(name: str) -> int | None:
    from .normalize import fold

    key = fold(name)
    if key.isdigit():
        n = int(key)
        return n if 1 <= n <= 114 else None
    return ALIASES.get(key)


def display(n: int) -> str:
    return NAMES_FA.get(n, str(n))
